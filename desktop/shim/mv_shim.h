// ===========================================================================
// mv_shim.h — MoonViz 自渲染系统 I/O 统一契约（客户端引导模型）
// ===========================================================================
// 定位（强制）：引擎【无 UI、无窗口、不自行获取渲染面】。自渲染能力必须由
// 客户端引导使用——客户端（Tauri / Electron / 任意原生壳）拥有 webview 并
// 承载渲染面；引擎只做两件事：
//   1. 按引导渲染：.mbt.md → 引擎管线 → 自包含交互 HTML，结果交给客户端
//      （客户端把产物载入自己的 webview，即获得活原型）；
//   2. 系统兜底：客户端没有 webview 的原生环境，引擎直接调用系统层渲染并
//      返回结果（产物写盘 / stdout）。
// 因此本契约只有系统 I/O：读渲染源、写兜底产物、环境变量。webview 的创建、
// 窗口、事件泵全部属于客户端——引擎侧不存在任何 UI 符号。
//
// 单文件实现（shim/desktop_io.c）：纯 C 标准库（stdio/stdlib），三平台无
// 差异、零框架链接。字符串约定：UTF-8；C→MoonBit 回传一律经
// moonbit_make_string 产出 GC 串。内存：本契约不外借 malloc 指针；
// mv_free 保留给未来确需外借暂存的场景（NULL 安全）。
// ===========================================================================

#ifndef MV_SHIM_H
#define MV_SHIM_H

// ---- 环境（客户端引导的开关经 env 传入，不经命令行参数）------------------
// 取环境变量（UTF-8）；未设置返回 ""。
moonbit_string_t mv_getenv(const char *name);

// ---- 渲染源读取（客户端引导：MOONVIZ_DOC 指向 .mbt.md 唯一事实源）--------
// 读整个文本文件为 moonbit GC 串（UTF-8，严格解码：非法序列回退 U+FFFD）；
// 不可读或含内嵌 NUL（非文本源）返回 ""。
moonbit_string_t mv_read_file(const char *path_utf8);

// ---- 兜底产物写出（第二层：系统层渲染返回结果）----------------------------
// 写文本文件（UTF-8，显式字节长度 data[0..len)：不依赖 NUL 终止、内嵌内容
// 不截断；整文件覆盖；父目录须已存在）。len < 0 视为非法。返回 0 / -1。
int mv_write_file(const char *path_utf8, const char *data_utf8, int len);

// ---- 内存 -----------------------------------------------------------------
// 释放 shim malloc 暴露给外部的指针（如有）；NULL 安全。
void mv_free(char *ptr);

// ---- 进程退出 --------------------------------------------------------------
// 终止进程（不返回）：smoke 自检失败经此非零退出，不解析 stdout 的调用方
// （CI 门禁）也能感知失败。0 = 成功，非 0 = 失败。
void mv_exit(int code);

#endif // MV_SHIM_H
